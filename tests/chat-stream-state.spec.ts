test('quitter pendant une lecture libère le flux sans afficher une erreur', async ({ page }) => {
  const evidence = await mountChat(page)
  await sendQuestion(page)
  await requests(page, 1)
  await replyStream(page, 0, [{ type: 'text', content: 'Début de réponse.' }], false)
  await expect(page.getByText('Début de réponse.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Quitter la conversation' }).click()
  await expect.poll(() => page.evaluate(() => window.chatCancellations[0])).toBe(1)
  expect(await page.evaluate(() => window.chatRequests[0].options.signal?.aborted)).toBe(true)
  await settleUI(page)
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.locator('[data-sonner-toast]')).toHaveCount(0)
  expect(await page.evaluate(() => window.chatRequests.length)).toBe(1)
  expect(evidence).toEqual({ external: [], errors: [] })
})

