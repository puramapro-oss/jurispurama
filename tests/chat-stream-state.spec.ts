import { expect, test } from '@playwright/test'
import { mountChat, replyCase, replyStream, requests, sendQuestion, settleUI } from './chat-stream-fixture'

test('le flux courant conserve le texte, les actions et le dossier créé', async ({ page }) => {
  const evidence = await mountChat(page)
  await sendQuestion(page)
  await requests(page, 1)
  await replyStream(page, 0, [
    { type: 'case_created', caseId: 'created-case' },
    { type: 'text', content: 'Réponse courante.' },
    { type: 'done', caseId: 'created-case', meta: { next_actions: ['generate_document'] } },
  ])
  await requests(page, 2)
  await replyCase(page, 1, 'created-case')
  await expect(page.getByTestId('streaming')).toHaveText('Réponse terminée')
  await expect(page.getByText('Réponse courante.', { exact: true })).toBeVisible()
  await expect(page.getByText('generate_document', { exact: true })).toBeVisible()
  await expect(page.getByTestId('case-summary')).toHaveText('Dossier created-case')
  await expect(page).toHaveURL('https://chat-fixture.invalid/chat/created-case')
  await sendQuestion(page)
  await requests(page, 3)
  expect(await page.evaluate(() => JSON.parse(String(window.chatRequests[2].options.body)).caseId)).toBe('created-case')
  expect(evidence).toEqual({ external: [], errors: [] })
})

